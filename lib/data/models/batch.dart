// lib/data/models/batch.dart
//
// Immutable data model representing a single egg-incubation batch.
//
// A batch document lives in Firestore at:
//   batches/{batchId}
//
// and has the following lifecycle:
//   created (status = 'active')  →  ended (status = 'ended')
//
// Day counting follows the convention: Day 1 = placedDate.

import 'package:cloud_firestore/cloud_firestore.dart';

import '../../core/extensions.dart';

/// Represents one egg-incubation batch, as stored in Firestore.
///
/// All fields are immutable; use [copyWith] to produce modified copies.
class Batch {
  /// Firestore document ID (auto-generated by Firestore on creation).
  final String id;

  /// ISO date string ('yyyy-MM-dd') in Kolkata time for the day the eggs
  /// were placed in the incubator.  Day 1 of the 21-day cycle.
  final String placedDate;

  /// Number of eggs placed in the incubator for this batch.
  final int eggCount;

  /// Lifecycle status.  One of:
  ///   - `'active'`  – batch is currently running; alarms are active.
  ///   - `'ended'`   – batch has been manually ended or completed.
  final String status;

  /// Display name of the user who created this batch.
  final String createdBy;

  /// Firestore server timestamp recording when the batch document was created.
  final Timestamp createdAt;

  const Batch({
    required this.id,
    required this.placedDate,
    required this.eggCount,
    required this.status,
    required this.createdBy,
    required this.createdAt,
  });

  // ---------------------------------------------------------------------------
  // Firestore ↔ Dart conversion
  // ---------------------------------------------------------------------------

  /// Constructs a [Batch] from a Firestore [DocumentSnapshot].
  ///
  /// Throws [StateError] if any required field is missing.
  factory Batch.fromFirestore(DocumentSnapshot doc) {
    final data = doc.data() as Map<String, dynamic>;
    return Batch(
      id: doc.id,
      placedDate: data['placedDate'] as String,
      eggCount: (data['eggCount'] as num).toInt(),
      status: data['status'] as String,
      createdBy: data['createdBy'] as String,
      createdAt: data['createdAt'] as Timestamp,
    );
  }

  /// Serialises this [Batch] to a plain Dart map suitable for Firestore writes.
  ///
  /// Note: [id] is intentionally excluded – Firestore uses the document path
  /// as the identifier and does not store it inside the document body.
  Map<String, dynamic> toMap() => {
        'placedDate': placedDate,
        'eggCount': eggCount,
        'status': status,
        'createdBy': createdBy,
        'createdAt': createdAt,
      };

  // ---------------------------------------------------------------------------
  // Business logic
  // ---------------------------------------------------------------------------

  /// Returns the **1-based** day number relative to [nowKolkata].
  ///
  /// Day 1 is [placedDate] itself.  Returns 1 even if [nowKolkata] is before
  /// midnight of [placedDate] (edge case: device clock wrong).
  /// Returns [kIncubationDays] + 1 after hatching day to signal completion.
  ///
  /// [nowKolkata] must be in Kolkata timezone (use [nowKolkata()] from
  /// extensions.dart).
  int daysElapsed(DateTime nowKolkata) {
    final placed = placedDate.toKolkataDateTime();
    // Truncate both sides to midnight to get a clean day difference.
    final placedMidnight =
        DateTime(placed.year, placed.month, placed.day);
    final nowMidnight =
        DateTime(nowKolkata.year, nowKolkata.month, nowKolkata.day);
    final diff = nowMidnight.difference(placedMidnight).inDays;
    // Day 1 = diff 0, Day 2 = diff 1, …
    return (diff + 1).clamp(1, 999);
  }

  // ---------------------------------------------------------------------------
  // copyWith
  // ---------------------------------------------------------------------------

  /// Returns a copy of this [Batch] with the specified fields replaced.
  Batch copyWith({
    String? id,
    String? placedDate,
    int? eggCount,
    String? status,
    String? createdBy,
    Timestamp? createdAt,
  }) {
    return Batch(
      id: id ?? this.id,
      placedDate: placedDate ?? this.placedDate,
      eggCount: eggCount ?? this.eggCount,
      status: status ?? this.status,
      createdBy: createdBy ?? this.createdBy,
      createdAt: createdAt ?? this.createdAt,
    );
  }

  @override
  String toString() =>
      'Batch(id=$id, placedDate=$placedDate, eggCount=$eggCount, '
      'status=$status, createdBy=$createdBy)';

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is Batch && runtimeType == other.runtimeType && id == other.id;

  @override
  int get hashCode => id.hashCode;
}
